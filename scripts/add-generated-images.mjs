// Adds client-generated images (YHC_IMAGE_PROMPTS.md) to the site.
// Put files named by slot ID (H01.png, P02w.png, C03.jpg …) in YHC-assets/generated/, then run:
//   node scripts/add-generated-images.mjs
// Each image is resized (max 1600 px wide) to WebP q82 in public/media/gen/<id>.webp, and
// src/lib/generated-images.ts is rewritten so the matching slots switch from fallback to the new image.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, parse } from 'node:path';

const pnpmDir = join(process.cwd(), 'node_modules', '.pnpm');
const sharpDir = readdirSync(pnpmDir).find((d) => d.startsWith('sharp@'));
if (!sharpDir) throw new Error('sharp not found');
const sharp = createRequire(import.meta.url)(join(pnpmDir, sharpDir, 'node_modules', 'sharp'));

const SRC = join('YHC-assets', 'generated');
const OUT = join('public', 'media', 'gen');
const ID = /^[A-Z]\d{2}w?$/;
mkdirSync(OUT, { recursive: true });
if (!existsSync(SRC)) {
  console.log(`No ${SRC} folder yet — nothing to add.`);
  process.exit(0);
}

const manifest = {};
for (const file of readdirSync(SRC).sort()) {
  const { name, ext } = parse(file);
  if (!/\.(png|jpe?g|webp)$/i.test(ext)) continue;
  const id = name.trim().toUpperCase().replace(/W$/, 'w');
  if (!ID.test(id)) {
    console.warn(`skip ${file}: name it by slot ID, e.g. H01.png`);
    continue;
  }
  const info = await sharp(join(SRC, file))
    .rotate()
    .resize({ width: 1600, withoutEnlargement: true })
    .webp({ quality: 82, effort: 5 })
    .toFile(join(OUT, `${id}.webp`));
  manifest[id] = { width: info.width, height: info.height };
  console.log(`${id}\t${info.width}x${info.height}\t${Math.round(info.size / 1024)} KB`);
}

const body = Object.entries(manifest)
  .map(([id, d]) => `  ${id}: { width: ${d.width}, height: ${d.height} },`)
  .join('\n');
writeFileSync(
  join('src', 'lib', 'generated-images.ts'),
  `/*\n * GENERATED by scripts/add-generated-images.mjs — do not edit by hand.\n * Images the client generated from YHC_IMAGE_PROMPTS.md, optimised into public/media/gen/<id>.webp.\n * A slot listed here replaces its temporary image (src/lib/visual-slots.ts).\n */\nexport const GENERATED_IMAGES: Record<string, { width: number; height: number }> = {${body ? `\n${body}\n` : ''}};\n`,
);
console.log(`${Object.keys(manifest).length} images added.`);
